"""Generate backend/app/services/country_codes.py from GeoNames countryInfo.txt.

Usage: python scripts/gen_country_codes.py
"""

import hashlib
import re
import urllib.request
from pathlib import Path

URL = "https://download.geonames.org/export/dump/countryInfo.txt"
OUT = Path(__file__).resolve().parents[1] / "backend/app/services/country_codes.py"

# FIPS 10-4 codes GDELT uses that GeoNames lacks or maps to a withdrawn ISO code,
# applied after the GeoNames pairs. "" leaves the FIPS code unmapped.
# Still unmapped on purpose, as they have no ISO code: ocean and undersea
# features, the Paracel and Spratly Islands, and no-man's-land areas.
OVERRIDES = {
    # GDELT uses FIPS GZ for the Gaza Strip, but GeoNames lists only WE (West
    # Bank) for ISO PS. ISO PS covers both Palestinian territories.
    "GZ": "PS",
    "JN": "SJ",  # Jan Mayen (ISO SJ: Svalbard and Jan Mayen)
    # US Minor Outlying Islands (ISO UM)
    "FQ": "UM",  # Baker Island
    "HQ": "UM",  # Howland Island
    "DQ": "UM",  # Jarvis Island
    "JQ": "UM",  # Johnston Atoll
    "KQ": "UM",  # Kingman Reef
    "MQ": "UM",  # Midway Islands
    "LQ": "UM",  # Palmyra Atoll
    "WQ": "UM",  # Wake Island
    "BQ": "UM",  # Navassa Island
    # French Southern Territories (ISO TF): the Scattered Islands
    "BS": "TF",  # Bassas da India
    "EU": "TF",  # Europa Island
    "GO": "TF",  # Glorioso Islands
    "JU": "TF",  # Juan de Nova Island
    "TE": "TF",  # Tromelin Island
    # Australian external territories (ISO AU)
    "AT": "AU",  # Ashmore and Cartier Islands
    "CR": "AU",  # Coral Sea Islands
    # GeoNames maps these to withdrawn ISO codes, so leave them unmapped.
    "NT": "",  # Netherlands Antilles (ISO AN, withdrawn 2010)
    "YI": "",  # Serbia and Montenegro (ISO CS, withdrawn 2006)
}

# OVERRIDES keys allowed to replace an existing GeoNames mapping. Removals
# ("" values, such as NT and YI) are deliberate by definition and need no entry.
DELIBERATE_REPLACEMENTS: set[str] = set()

ANCHORS = {"SP": "ES", "UK": "GB", "CH": "CN", "GM": "DE", "AS": "AU"}


def check(ok: bool, message: str) -> None:
    if not ok:
        raise SystemExit(f"refusing to write {OUT.name}: {message}")


raw = urllib.request.urlopen(URL, timeout=30).read()
sha256 = hashlib.sha256(raw).hexdigest()
pairs: dict[str, str] = {}
for line in raw.decode("utf-8").splitlines():
    if not line or line.startswith("#"):
        continue
    cols = line.split("\t")
    iso, fips = cols[0].strip(), cols[3].strip()
    if iso and fips:
        check(fips not in pairs, f"FIPS {fips} is listed for both {pairs.get(fips)} and {iso}")
        pairs[fips] = iso

collisions = sorted(
    f"{fips} (GeoNames {pairs[fips]}, override {iso})"
    for fips, iso in OVERRIDES.items()
    if iso and fips in pairs and fips not in DELIBERATE_REPLACEMENTS
)
check(not collisions, f"overrides replace GeoNames codes: {collisions}")

for fips, iso in OVERRIDES.items():
    if iso:
        pairs[fips] = iso
    else:
        pairs.pop(fips, None)

check(240 <= len(pairs) <= 270, f"{len(pairs)} codes, expected 240 to 270")
for fips, iso in ANCHORS.items():
    check(pairs.get(fips) == iso, f"FIPS {fips} maps to {pairs.get(fips)!r}, expected {iso}")
two_letters = re.compile(r"[A-Z]{2}")
bad = sorted(
    f"{f}->{i}"
    for f, i in pairs.items()
    if not (two_letters.fullmatch(f) and two_letters.fullmatch(i))
)
check(not bad, f"malformed codes: {bad}")

body = "\n".join(f'    "{f}": "{i}",' for f, i in sorted(pairs.items()))
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write(
        '"""FIPS 10-4 (GDELT) to ISO 3166-1 alpha-2 country codes.\n\n'
        "Generated by scripts/gen_country_codes.py from GeoNames countryInfo.txt\n"
        "plus the overrides in that script. Do not edit by hand.\n\n"
        f"Source: {URL}\n"
        f"Source SHA-256: {sha256}\n"
        '"""\n\nfrom __future__ import annotations\n\n'
        f"FIPS_TO_ISO2: dict[str, str] = {{\n{body}\n}}\n\n\n"
        "def fips_to_iso2(fips: str | None) -> str:\n"
        '    """Return the ISO alpha-2 code for a GDELT FIPS code, or "" if unknown."""\n'
        '    return FIPS_TO_ISO2.get((fips or "").strip().upper(), "")\n'
    )
print(f"wrote {len(pairs)} codes to {OUT}")
